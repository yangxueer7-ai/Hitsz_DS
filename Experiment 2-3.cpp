// ========题目3 二叉树的最大路径和 =========
/*
题目思路：
本题要求二叉树中的最大路径和，路径可以从任意节点开始，到任意节点结束，
不一定经过根节点，但同一个节点最多只能出现一次。

采用递归后序遍历。对于每个节点，先计算左右子树能向当前节点提供的最大单侧贡献。
如果某一侧贡献为负数，则接上它会使路径和变小，因此将其贡献记为 0。

经过当前节点的最大路径和为：
当前节点值 + 左子树贡献 + 右子树贡献。
用该值更新全局最大路径和 ans。

但当前节点向父节点返回时，路径不能分叉，
所以只能返回：
当前节点值 + max(左子树贡献, 右子树贡献)。

递归遍历完整棵树后，ans 即为最大路径和。
*/